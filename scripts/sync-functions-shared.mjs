#!/usr/bin/env node
// Copies dependency-free shared modules into supabase/functions/_shared, because the Edge
// Runtime can only load files inside supabase/functions. Run after editing the source:
//
//   pnpm sync:functions
//
// supabase/functions/_shared/notification-text.sync.test.ts fails when a copy is stale.

import { readFileSync, writeFileSync } from "node:fs";

export const SYNCED = [["packages/shared/src/notification-text.ts", "supabase/functions/_shared/notification-text.ts"]];

export const BANNER = "// GENERATED by scripts/sync-functions-shared.mjs from packages/shared. Do not edit here.\n";

const root = new URL("../", import.meta.url);

if (process.argv[1]?.endsWith("sync-functions-shared.mjs")) {
  for (const [from, to] of SYNCED) {
    writeFileSync(new URL(to, root), BANNER + readFileSync(new URL(from, root), "utf8"));
    console.log(`synced ${from} -> ${to}`);
  }
}
